package tabloid;

import org.antlr.v4.runtime.ParserRuleContext;
import org.antlr.v4.runtime.tree.ParseTree;
import tabloid.parser.TabloidBaseVisitor;
import tabloid.parser.TabloidParser;
import java.math.BigInteger;
import java.util.*;

/** Visitor emitter: every infix tree node is explicitly parenthesized. */
public final class PythonEmitter extends TabloidBaseVisitor<String> {
    private int indentation;
    private int functionDepth;
    private String pad() { return "    ".repeat(indentation); }
    private static String name(String value) { return "_t_" + value; }
    private static CompileException error(ParserRuleContext ctx, String message) {
        return new CompileException(ctx.start.getLine() + ":" + (ctx.start.getCharPositionInLine() + 1) + ": " + message);
    }

    @Override public String visitProgram(TabloidParser.ProgramContext ctx) {
        StringBuilder out = new StringBuilder("# Generated by tabloid-to-python-compiler. Review before running.\n");
        for (var statement : ctx.statement()) out.append(visit(statement));
        if (ctx.statement().isEmpty()) out.append("pass\n");
        return out.toString();
    }
    @Override public String visitAssignment(TabloidParser.AssignmentContext ctx) {
        return pad() + name(ctx.ID().getText()) + " = " + visit(ctx.expression()) + "\n";
    }
    @Override public String visitPrintStmt(TabloidParser.PrintStmtContext ctx) {
        return pad() + "print(" + visit(ctx.expression()) + ")\n";
    }
    @Override public String visitExpressionStmt(TabloidParser.ExpressionStmtContext ctx) {
        return pad() + visit(ctx.expression()) + "\n";
    }
    @Override public String visitReturnStmt(TabloidParser.ReturnStmtContext ctx) {
        if (functionDepth == 0) throw error(ctx, "Return is only valid inside a function");
        return pad() + "return" + (ctx.expression() == null ? "" : " " + visit(ctx.expression())) + "\n";
    }
    @Override public String visitFunctionDecl(TabloidParser.FunctionDeclContext ctx) {
        List<String> parameters = new ArrayList<>();
        Set<String> seen = new HashSet<>();
        if (ctx.paramList() != null) {
            for (var id : ctx.paramList().ID()) {
                if (!seen.add(id.getText())) throw error(ctx, "Duplicate parameter: " + id.getText());
                parameters.add(name(id.getText()));
            }
        }
        String header = pad() + "def " + name(ctx.ID().getText()) + "(" + String.join(", ", parameters) + "):\n";
        functionDepth++;
        indentation++;
        try { return header + visit(ctx.block()); }
        finally { functionDepth--; indentation--; }
    }
    @Override public String visitBlock(TabloidParser.BlockContext ctx) {
        if (ctx.statement().isEmpty()) return pad() + "pass\n";
        StringBuilder out = new StringBuilder();
        for (var statement : ctx.statement()) out.append(visit(statement));
        return out.toString();
    }
    @Override public String visitSuite(TabloidParser.SuiteContext ctx) {
        return ctx.block() != null ? visit(ctx.block()) : visit(ctx.statement());
    }
    private String indented(ParseTree suite) {
        indentation++;
        try { return visit(suite); }
        finally { indentation--; }
    }
    @Override public String visitIfStmt(TabloidParser.IfStmtContext ctx) {
        String output = pad() + "if " + visit(ctx.expression()) + ":\n" + indented(ctx.suite(0));
        if (ctx.suite().size() == 2) output += pad() + "else:\n" + indented(ctx.suite(1));
        return output;
    }
    @Override public String visitWhileStmt(TabloidParser.WhileStmtContext ctx) {
        return pad() + "while " + visit(ctx.expression()) + ":\n" + indented(ctx.block());
    }
    @Override public String visitExpression(TabloidParser.ExpressionContext ctx) { return visit(ctx.orExpr()); }
    @Override public String visitOrExpr(TabloidParser.OrExprContext ctx) { return fold(ctx); }
    @Override public String visitAndExpr(TabloidParser.AndExprContext ctx) { return fold(ctx); }
    @Override public String visitComparison(TabloidParser.ComparisonContext ctx) { return fold(ctx); }
    @Override public String visitAdditive(TabloidParser.AdditiveContext ctx) { return fold(ctx); }
    @Override public String visitMultiplicative(TabloidParser.MultiplicativeContext ctx) { return fold(ctx); }
    private String fold(ParserRuleContext ctx) {
        String value = visit(ctx.getChild(0));
        for (int i = 1; i < ctx.getChildCount(); i += 2) {
            String operator = ctx.getChild(i).getText().replaceAll("\\s+", " ");
            String python = switch (operator) {
                case "OR" -> "or"; case "AND" -> "and";
                case "IS ACTUALLY" -> "=="; case "BEATS" -> ">";
                case "SMALLER THAN", "IS SMALLER THAN" -> "<";
                case "PLUS" -> "+"; case "MINUS" -> "-"; case "TIMES" -> "*";
                case "DIVIDED BY" -> "/"; case "MODULO" -> "%";
                default -> throw error(ctx, "Unsupported operator");
            };
            value = "(" + value + " " + python + " " + visit(ctx.getChild(i + 1)) + ")";
        }
        return value;
    }
    @Override public String visitUnary(TabloidParser.UnaryContext ctx) {
        return ctx.MINUS() == null ? visit(ctx.primary()) : "(-" + visit(ctx.unary()) + ")";
    }
    @Override public String visitPrimary(TabloidParser.PrimaryContext ctx) {
        if (ctx.ID() != null) return name(ctx.ID().getText());
        if (ctx.functionCall() != null) return visit(ctx.functionCall());
        if (ctx.inputExpr() != null) return visit(ctx.inputExpr());
        if (ctx.literal() != null) return visit(ctx.literal());
        return "(" + visit(ctx.expression()) + ")";
    }
    @Override public String visitFunctionCall(TabloidParser.FunctionCallContext ctx) {
        List<String> args = new ArrayList<>();
        for (var expression : ctx.expression()) args.add(visit(expression));
        return name(ctx.ID().getText()) + "(" + String.join(", ", args) + ")";
    }
    @Override public String visitInputExpr(TabloidParser.InputExprContext ctx) {
        return "input(" + visit(ctx.expression()) + ")";
    }
    @Override public String visitLiteral(TabloidParser.LiteralContext ctx) {
        if (ctx.TRUE_LITERAL() != null) return "True";
        if (ctx.FALSE_LITERAL() != null) return "False";
        if (ctx.NUMBER() != null) {
            String text = ctx.NUMBER().getText();
            if (text.length() > 256) throw error(ctx, "Number literal exceeds 256 characters");
            String[] parts = text.split("\\.", 2);
            return new BigInteger(parts[0]).toString() + (parts.length == 2 ? "." + parts[1] : "");
        }
        String raw = ctx.STRING().getText();
        StringBuilder decoded = new StringBuilder();
        for (int i = 1; i < raw.length() - 1; i++) {
            char value = raw.charAt(i);
            if (value == '\\') {
                value = switch (raw.charAt(++i)) {
                    case 'n' -> '\n'; case 'r' -> '\r'; case 't' -> '\t';
                    case '\\' -> '\\'; case '\'' -> '\'';
                    default -> throw error(ctx, "Unsupported string escape");
                };
            }
            decoded.append(value);
        }
        // Quote the decoded value instead of copying source text into executable Python.
        StringBuilder quoted = new StringBuilder("'");
        decoded.toString().codePoints().forEach(cp -> {
            switch (cp) {
                case '\'' -> quoted.append("\\'"); case '\\' -> quoted.append("\\\\");
                case '\n' -> quoted.append("\\n"); case '\r' -> quoted.append("\\r"); case '\t' -> quoted.append("\\t");
                default -> {
                    if (Character.isISOControl(cp)) quoted.append(String.format(Locale.ROOT, "\\u%04x", cp));
                    else quoted.appendCodePoint(cp);
                }
            }
        });
        return quoted.append("'").toString();
    }
}
